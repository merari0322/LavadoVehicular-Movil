// llaves de un objeto de traducciones, con su ruta (A.B.C)
function keysOf(node: object, prefix = ''): string[] {
  return Object.entries(node).flatMap(([key, value]) =>
    value && typeof value === 'object' ? keysOf(value, `${prefix}${key}.`) : [`${prefix}${key}`],
  );
}

describe('códigos de error del backend (MOV-06)', () => {
  it('cada código que lanza un backend tiene su mensaje propio', () => {
    const missing = Object.values(BACKEND_CODES)
      .flatMap((list) => list.split(' '))
      .filter((code) => new ApiError(code, 400).messageKey !== `API_ERRORS.${code}`);
    expect(missing).toEqual([]);
  });

  it('los mensajes de error están en los 4 idiomas', () => {
    const base = keysOf(es.API_ERRORS).sort();
    expect(keysOf(en.API_ERRORS).sort()).toEqual(base);
    expect(keysOf(fr.API_ERRORS).sort()).toEqual(base);
    expect(keysOf(pt.API_ERRORS).sort()).toEqual(base);
  });

  it('los 2 códigos del contrato pago-reserva y el motivo PAYMENT_TIMEOUT están en los 4 idiomas', () => {
    for (const locale of [es, en, fr, pt]) {
      expect(locale.API_ERRORS.CASH_BOOKING_LIMIT).toBeTruthy();
      expect(locale.API_ERRORS.INVALID_PAYMENT_MODE).toBeTruthy();
      expect(locale.CANCELLATION_REASONS.PAYMENT_TIMEOUT).toBeTruthy();
    }
    expect(new ApiError('CASH_BOOKING_LIMIT', 409).messageKey).toBe('API_ERRORS.CASH_BOOKING_LIMIT');
    expect(new ApiError('INVALID_PAYMENT_MODE', 400).messageKey).toBe('API_ERRORS.INVALID_PAYMENT_MODE');
  });

  it('un código sin traducción usa el mensaje de su estado HTTP, no "error inesperado"', () => {
    expect(new ApiError('HTTP_404', 404).messageKey).toBe('API_ERRORS.NOT_FOUND');
    expect(new ApiError('HTTP_503', 503).messageKey).toBe('API_ERRORS.SERVICE_UNAVAILABLE');
    expect(new ApiError('HTTP_429', 429).messageKey).toBe('API_ERRORS.RATE_LIMITED');
    expect(new ApiError('METHOD_NOT_ALLOWED', 405).messageKey).toBe('API_ERRORS.UNEXPECTED');
    expect(apiErrorKey(new Error('cualquiera'))).toBe('API_ERRORS.UNEXPECTED');
  });

  it('un 400 de validación dice qué campo revisar si es uno conocido', () => {
    const notes = new ApiError('VALIDATION_ERROR', 400, [], { code: 'VALIDATION_ERROR', errors: { notes: 'size must be between 0 and 300' } });
    expect(notes.messageKey).toBe('API_ERRORS.FIELDS.NOTES');
    expect(notes.fieldErrors).toEqual({ notes: 'size must be between 0 and 300' });
    const unknown = new ApiError('VALIDATION_ERROR', 400, [], { errors: { foo: 'x' } });
    expect(unknown.messageKey).toBe('API_ERRORS.VALIDATION_ERROR');
  });
});

describe('httpClient con el mapa errors de un 400', () => {
  const fetchMock = jest.fn();
  beforeEach(() => {
    fetchMock.mockReset();
    globalThis.fetch = fetchMock as unknown as typeof fetch;
    registerAuthHooks({ getToken: () => 'token', onUnauthorized: jest.fn() });
  });

  it('payment-service (ASP.NET) manda el mapa sin code: queda como VALIDATION_ERROR con sus campos', async () => {
    fetchMock.mockResolvedValue({
      ok: false,
      status: 400,
      text: () => Promise.resolve(JSON.stringify({ title: 'One or more validation errors occurred.', errors: { TransactionReference: ['Too long'] } })),
    } as Response);

    const error = await request('POST', '/payments', { body: {} }).catch((e: unknown) => e);

    expect(error).toBeInstanceOf(ApiError);
    expect((error as ApiError).code).toBe('VALIDATION_ERROR');
    expect((error as ApiError).fieldErrors).toEqual({ TransactionReference: 'Too long' });
    expect((error as ApiError).messageKey).toBe('API_ERRORS.FIELDS.REFERENCE');
  });
});
